#!/usr/bin/env python3
"""d2r-mobile documentation gate — the same mechanical criteria as the family.

Generated by the `init-dsh-project` skill (version 1.8, 2026-10-26).
**It belongs to this repo**: change it when this repo's criteria change.
Canonical source and the family-wide yardstick:
`~/code/nan-fedora/dot_claude/skills/{init-dsh-project,docs-check}/`.

Three criteria (identical to the family — do not invent your own):

1. **Entry-file budget** — `CLAUDE.md` (+ an optional `CLAUDE.local.md`) is capped at
   65536 bytes. Past the cap nothing errors: the host **silently truncates the tail**, and the
   first casualties are the last-written sections (Commit style, New work checklist).
   **One entry file on purpose.** DSH loads both `AGENTS.md` and `CLAUDE.md` from the same tree;
   identical content renders once but **counts its bytes twice**, so a second file only reliably
   buys a second copy to drift. A pre-existing `AGENTS.md` is therefore still counted (same host,
   same budget) and reported as a `warn` — never ignored, because ignoring it opens a back door
   in the budget. Repos that legitimately keep both (the family yardstick reads every repo) stay
   supported: the budget takes the **sum**, the section check takes the **union**.
2. **Bidirectional index** — for `docs/{adr,issues}/README.md`: every `NNN-*.md` has a row, and
   every row points at a file that exists.
3. **No in-repo dead links** — relative links resolve by **number prefix first, then unique
   basename** (a renamed slug must not read as a broken link). Cross-repo references are written
   as greppable coordinates (`<repo> issue NNN`), never as relative paths the gate cannot resolve.

Plus: tier-required files (`--tier`, see `reference/tiering.md`).

Usage:

    python3 tools/dev/check_docs.py                 # human-readable, exit 1 on any fail
    python3 tools/dev/check_docs.py --tier 2        # also check tier-required files
    python3 tools/dev/check_docs.py --json          # structured (CI / other scripts)
    python3 tools/dev/check_docs.py --only budget   # run one check family
    python3 tools/dev/check_docs.py --explain       # print why each criterion exists

Standard library only. **No external commands** (`diff` / `find` / `grep`): on this fleet the
bare `diff` is shadowed by an x86_64 toolchain binary and dies with `Exec format error`, so the
gate must not depend on whatever happens to be on PATH.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

BUDGET_BYTES = 65536  # family constant: CLAUDE.md (+ CLAUDE.local.md) combined cap
# One entry file per repo (see §1). A pre-existing `AGENTS.md` is still loaded by the same host
# and still consumes the same budget, so it counts — and it is reported, never silently ignored.
ENTRY_BASE = ["CLAUDE.md"]
ENTRY_LOCAL = ["CLAUDE.local.md"]
LEGACY_ENTRY = ["AGENTS.md", "AGENTS.local.md"]

# Tier-required files (relative to the repo root; globs allowed) — same source as
# docs-check's Appendix C.
TIER_REQUIRED = {
    0: ["CLAUDE.md"],
    1: [
        "CLAUDE.md",
        "README.md",
        "docs/index.md",
        "docs/*-positioning.md",
        "docs/*-architecture.md",
        "docs/adr/README.md",
        "docs/issues/README.md",
        "docs/agents/issue-tracker.md",
        "docs/agents/triage-labels.md",
    ],
    2: [
        "CLAUDE.md",
        "README.md",
        "CHANGELOG.md",
        "CONTEXT.md",
        "docs/index.md",
        "docs/*-positioning.md",
        "docs/*-design-philosophy.md",
        "docs/*-architecture.md",
        "docs/adr/README.md",
        "docs/adr/0000-template.md",
        "docs/issues/README.md",
        "docs/issues/0000-template.md",
        "docs/agents/issue-tracker.md",
        "docs/agents/triage-labels.md",
        "docs/agents/domain.md",
    ],
}

# Directories whose numbered files must be indexed, both ways
INDEXED_DIRS = ["docs/adr", "docs/issues"]

NUM_NAME_RE = re.compile(r"^(\d{3,4})-.*\.md$")
MD_LINK_RE = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
INDEX_ROW_RE = re.compile(r"^\s*\|")
SKIP_LINK_PREFIX = ("http://", "https://", "mailto:", "#", "//")
# Directories the gate must never scan. `repos/` holds read-only upstream clones (third-party
# code and third-party dead links — not ours to fix) and `data/` holds generated datasets
# (gitignored, machine-specific). Scanning either produces findings nobody can act on, and a gate
# that reports un-actionable failures trains its readers to ignore it.
SKIP_PATH_PARTS = {".git", "node_modules", "target", ".venv", "__pycache__", "dist", "build",
                   "repos", "data", "runs", "results", ".hf-cache"}

DEFAULT_CONFIG = {
    "tier": None,
    "budget_bytes": BUDGET_BYTES,
    "ignore_link_globs": [],
    "allow_missing": [],
}

class Finding:
    __slots__ = ("kind", "severity", "path", "detail")

    def __init__(self, kind: str, severity: str, path: str, detail: str):
        self.kind, self.severity, self.path, self.detail = kind, severity, path, detail

    def as_dict(self) -> dict:
        return {"kind": self.kind, "severity": self.severity, "path": self.path, "detail": self.detail}

    def __str__(self) -> str:
        tag = "FAIL" if self.severity == "fail" else "WARN"
        return f"[{tag}] {self.kind}: {self.path} — {self.detail}"

def load_config(root: Path) -> dict:
    cfg = dict(DEFAULT_CONFIG)
    for name in (".docs-check.json", ".docs-check.toml"):
        p = root / name
        if not p.is_file():
            continue
        text = p.read_text(encoding="utf-8")
        if name.endswith(".json"):
            cfg.update(json.loads(text))
        else:
            # Minimal TOML subset: `key = value` (string / int / bool / string array). Enough.
            for raw in text.splitlines():
                line = raw.split("#", 1)[0].strip()
                if not line or "=" not in line:
                    continue
                k, v = (s.strip() for s in line.split("=", 1))
                if v.startswith("[") and v.endswith("]"):
                    cfg[k] = [s.strip().strip("\"'") for s in v[1:-1].split(",") if s.strip()]
                elif v.lower() in ("true", "false"):
                    cfg[k] = v.lower() == "true"
                elif re.fullmatch(r"-?\d+", v):
                    cfg[k] = int(v)
                else:
                    cfg[k] = v.strip("\"'")
    return cfg

def iter_markdown(root: Path, ignore_globs: list[str]) -> list[Path]:
    out: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PATH_PARTS and not d.startswith(".git")]
        for fn in filenames:
            if not fn.endswith(".md"):
                continue
            p = Path(dirpath) / fn
            rel = p.relative_to(root).as_posix()
            if any(Path(rel).match(g) for g in ignore_globs):
                continue
            out.append(p)
    return sorted(out)

def check_budget(root: Path, cfg: dict, findings: list[Finding]) -> dict:
    files = [root / n for n in ENTRY_BASE + ENTRY_LOCAL + LEGACY_ENTRY]
    present = [(p, p.stat().st_size) for p in files if p.is_file()]
    total = sum(size for _, size in present)
    limit = int(cfg["budget_bytes"])
    primary = [p for p, _ in present if p.name in ENTRY_BASE]
    if not present:
        findings.append(Finding(
            "entry-budget", "fail", "CLAUDE.md",
            "no entry file at all — DSH collects CLAUDE.md/AGENTS.md from the repo root down, "
            "so with none present the agent gets no instructions"))
    elif not primary:
        findings.append(Finding(
            "entry-budget", "fail", "CLAUDE.md",
            "CLAUDE.md is missing; only a legacy second file exists — rename it to CLAUDE.md "
            "(one entry file per repo, see the gate docstring §1)"))
    elif total > limit:
        over = total - limit
        findings.append(Finding(
            "entry-budget", "fail", "CLAUDE.md(+local)",
            f"{total} B > {limit} B (over by {over} B) ⇒ the host silently truncates the tail; "
            f"the last-written sections go first. Detail: "
            + ", ".join(f"{p.name}={s}" for p, s in present)))
    else:
        legacy = [n for n in LEGACY_ENTRY if (root / n).is_file()]
        if legacy:
            findings.append(Finding(
                "entry-legacy-second-file", "warn", ", ".join(legacy),
                "this repo keeps ONE entry file (CLAUDE.md). This file is loaded by the same host "
                "and counts against the same budget ⇒ either delete it, or leave a one-line pointer "
                "in CLAUDE.md (never a restatement)."))
        # Warn when headroom shrinks below one section's worth: the next edit breaks the cap.
        if limit - total < 4096:
            findings.append(Finding(
                "entry-budget", "warn", "CLAUDE.md(+local)",
                f"{total} B, only {limit - total} B of headroom left — the next section will break it"))
    return {"total_bytes": total, "limit": limit, "files": {p.name: s for p, s in present}}

def check_index(root: Path, cfg: dict, findings: list[Finding]) -> list[dict]:
    stats = []
    for d in INDEXED_DIRS:
        base = root / d
        if not base.is_dir():
            continue
        index = base / "README.md"
        # `0000-*` files are templates (ADR / issue), not records ⇒ no index row required.
        # That is a convention, not an exemption: templates must be named `0000-<slug>.md`.
        files = sorted(p.name for p in base.iterdir()
                       if p.is_file() and NUM_NAME_RE.match(p.name) and not p.name.startswith("0000-"))
        if not files and not index.is_file():
            continue
        if not index.is_file():
            findings.append(Finding("index-missing", "fail", d,
                                    f"{len(files)} numbered files but no {d}/README.md index"))
            continue
        text = index.read_text(encoding="utf-8")
        rows = [ln for ln in text.splitlines() if INDEX_ROW_RE.match(ln)]
        row_text = "\n".join(rows)
        # (1) every numbered file has a row
        for fn in files:
            if fn not in row_text and fn[:3] not in row_text:
                findings.append(Finding(
                    "index-orphan", "fail", f"{d}/{fn}",
                    "file exists but has no index row — a cold agent's first hop cannot see it"))
        # (2) every row's relative link lands on a file that exists
        for ln in rows:
            for link in MD_LINK_RE.findall(ln):
                if link.startswith(SKIP_LINK_PREFIX) or link.startswith("../"):
                    continue
                target = (base / link.split("#", 1)[0]).resolve()
                if not target.exists():
                    findings.append(Finding("index-deadlink", "fail", f"{d}/README.md",
                                            f"index row points at a file that does not exist: {link}"))
        stats.append({"dir": d, "files": len(files), "rows": len(rows),
                      "index": str(index.relative_to(root))})
    return stats

def link_resolver(root: Path, rel_path: str, link: str, all_md: list[Path]) -> bool:
    """Does a relative link resolve? Rename/move tolerant: number prefix first, then basename."""
    src_dir = (root / rel_path).parent
    raw = link.split("#", 1)[0].strip()
    if not raw:
        return True
    if (src_dir / raw).resolve().exists():
        return True
    base = Path(raw).name
    if not base or "." not in base:
        return True  # directory-style reference; the gate does not guess intent
    key = base.split("-", 1)[0] if NUM_NAME_RE.match(base) else None
    hits = []
    for p in all_md:
        if p.name == base:
            hits.append(p)
        elif key and p.name.startswith(key + "-") and p.parent.name in {d.split("/")[-1] for d in INDEXED_DIRS}:
            hits.append(p)
    return len(hits) >= 1

def check_links(root: Path, cfg: dict, findings: list[Finding]) -> int:
    docs = iter_markdown(root, cfg.get("ignore_link_globs", []))
    md_set = list(docs)
    for p in docs:
        rel = p.relative_to(root).as_posix()
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for link in MD_LINK_RE.findall(line):
                if link.startswith(SKIP_LINK_PREFIX):
                    continue
                if not link_resolver(root, rel, link, md_set):
                    findings.append(Finding("dead-link", "fail", f"{rel}:{i}",
                                            f"in-repo relative link does not resolve: {link}"))
    return len(docs)

def check_structure(root: Path, tier: int | None, findings: list[Finding]) -> list[str]:
    if tier is None:
        return []
    required = TIER_REQUIRED.get(tier, [])
    missing = []
    for rel in required:
        if "*" in rel:
            if not list(root.glob(rel)):
                missing.append(rel)
            continue
        if not (root / rel).exists():
            missing.append(rel)
    for rel in missing:
        findings.append(Finding("tier-missing", "fail", rel, f"tier {tier} requires this file"))
    return [r for r in required if r not in missing]

# --------------------------------------------------------------- repo-local conventions
# The checks above are the family's mechanical minimum: they hold for every project at this tier,
# so the skill ships them. A *repo-specific* convention does not fit here — "every dataset figure
# names its convention", "every rejected option records why" — and the observed outcome is that it
# gets checked once by hand when an issue closes, then rots.
#
# So the gate has exactly one seam. If `tools/dev/check_conventions.py` exists it is executed and
# its `run(root, findings)` is called with the same `findings` list, so a repo-local rule is then
# as permanent as a family one. That file is repo-owned: the skill writes it once as a stub and
# never overwrites it. A rule that turns out to hold for *every* project belongs upstream, here.
#
# Why a separate file and not a config table: the config parser is a deliberate minimal TOML
# subset (`key = value` only), and inventing a rule language for it would make the gate harder to
# read than the convention it checks. Python is something the repo already has.
LOCAL_CONVENTIONS = "tools/dev/check_conventions.py"

def check_conventions(root: Path, cfg: dict, findings: list[Finding]) -> int:
    """Run the repo's own convention checks, if it has any.

    An absent file means zero rules, not an error: a project that has not needed one must not be
    nagged for not having one.
    """
    path = root / LOCAL_CONVENTIONS
    if not path.is_file():
        return 0
    ns: dict = {
        "__name__": "check_conventions",
        "__file__": str(path),
        "Finding": Finding,
        # Hand the local rule the *same* file set the gate scans. A rule that walks the tree
        # itself will, sooner or later, walk `repos/` and report third-party dead links as ours —
        # the exact defect SKIP_PATH_PARTS was added for. Make the right thing the easy thing.
        "markdown_files": lambda: iter_markdown(root, cfg.get("ignore_link_globs", [])),
        "SKIP_PATH_PARTS": SKIP_PATH_PARTS,
    }
    exec(compile(path.read_text(encoding="utf-8"), str(path), "exec"), ns)  # noqa: S102
    run = ns.get("run")
    if not callable(run):
        findings.append(Finding("conventions-bad-module", "fail", LOCAL_CONVENTIONS,
                                "exists but defines no callable `run(root, findings)`"))
        return 0
    before = len(findings)
    n = run(root, findings)
    return int(n) if n is not None else len(findings) - before

