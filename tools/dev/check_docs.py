def main() -> int:
    ap = argparse.ArgumentParser(description="d2r-mobile documentation gate")
    ap.add_argument("command", nargs="?", default="check", choices=["check"])
    ap.add_argument("--root", default=None, help="repo root (defaults to two levels above this file)")
    ap.add_argument("--tier", type=int, default=None, choices=[0, 1, 2], help="also check tier-required files")
    ap.add_argument("--json", action="store_true", help="structured output")
    ap.add_argument("--only", action="append", default=[],
                    choices=["budget", "index", "links", "structure", "conventions"])
    ap.add_argument("--explain", action="store_true", help="print why each criterion exists")
    ap.add_argument("--strict", action="store_true", help="treat warns as failures")
    args = ap.parse_args()

    if args.explain and not args.json:
        for k, v in EXPLAIN.items():
            print(f"{k:26s} {v}")
        return 0

    root = Path(args.root).expanduser().resolve() if args.root else Path(__file__).resolve().parents[2]
    if not root.is_dir():
        print(f"root does not exist: {root}", file=sys.stderr)
        return 2

    cfg = load_config(root)
    tier = args.tier if args.tier is not None else cfg.get("tier")
    findings: list[Finding] = []
    stats: dict = {"root": str(root), "tier": tier}

    run = set(args.only) if args.only else {"budget", "index", "links", "structure", "conventions"}
    if "budget" in run:
        stats["budget"] = check_budget(root, cfg, findings)
    if "index" in run:
        stats["index"] = check_index(root, cfg, findings)
    if "links" in run:
        stats["markdown_files"] = check_links(root, cfg, findings)
    if "conventions" in run:
        stats["local_conventions"] = check_conventions(root, cfg, findings)
    if "structure" in run:
        stats["tier_checked"] = check_structure(root, tier, findings)

    fails = [f for f in findings if f.severity == "fail"]
    warns = [f for f in findings if f.severity == "warn"]

    if args.json:
        print(json.dumps({
            "ok": not fails and not (args.strict and warns),
            "stats": stats,
            "findings": [f.as_dict() for f in findings],
            "counts": {"fail": len(fails), "warn": len(warns)},
        }, ensure_ascii=False, indent=2))
    else:
        b = stats.get("budget", {})
        if b:
            limit = b.get("limit", BUDGET_BYTES)
            print(f"entry budget : {b.get('total_bytes', 0)} / {limit} B"
                  f" {'OK' if b.get('total_bytes', 0) <= limit else 'FAIL'}")
            if b.get("files"):
                print("               " + ", ".join(f"{k}={v}" for k, v in b["files"].items()))
        for row in stats.get("index", []):
            print(f"index        : {row['index']} — {row['files']} files / {row['rows']} rows")
        if "markdown_files" in stats:
            print(f"link scan    : {stats['markdown_files']} markdown files")
        if stats.get("local_conventions"):
            print(f"conventions  : {stats['local_conventions']} finding(s) from "
                  f"{LOCAL_CONVENTIONS}")
        for f in findings:
            print(str(f))
        print(f"\n{'FAIL' if fails or (args.strict and warns) else 'OK'} "
              f"fail={len(fails)} warn={len(warns)}"
              + (" (--strict: warns fail)" if args.strict else ""))

    return 1 if (fails or (args.strict and warns)) else 0

if __name__ == "__main__":
    raise SystemExit(main())
